CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_users_email ON users (email);

CREATE TABLE IF NOT EXISTS auth_sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_auth_sessions_user_id ON auth_sessions (user_id);
CREATE INDEX IF NOT EXISTS ix_auth_sessions_token_hash ON auth_sessions (token_hash);

CREATE TABLE IF NOT EXISTS user_profiles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    age INTEGER NOT NULL CHECK (age BETWEEN 1 AND 120),
    gender VARCHAR(16) NOT NULL,
    activity_level VARCHAR(20) NOT NULL,
    weight_lbs DOUBLE PRECISION NOT NULL CHECK (weight_lbs > 0),
    height_feet INTEGER NOT NULL CHECK (height_feet BETWEEN 1 AND 8),
    height_inches INTEGER NOT NULL CHECK (height_inches BETWEEN 0 AND 11),
    goal VARCHAR(32) NOT NULL,
    goal_pace VARCHAR(16),
    calorie_target DOUBLE PRECISION NOT NULL CHECK (calorie_target > 0),
    protein_target DOUBLE PRECISION NOT NULL CHECK (protein_target > 0),
    carb_target DOUBLE PRECISION NOT NULL CHECK (carb_target > 0),
    fat_target DOUBLE PRECISION NOT NULL CHECK (fat_target > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS meals (
    id SERIAL PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    meal_type VARCHAR(20) NOT NULL,
    logged_date DATE NOT NULL,
    food_name VARCHAR(255) NOT NULL,
    serving_size VARCHAR(120) NOT NULL,
    quantity DOUBLE PRECISION NOT NULL,
    calories DOUBLE PRECISION NOT NULL,
    protein_g DOUBLE PRECISION NOT NULL,
    carbs_g DOUBLE PRECISION NOT NULL,
    fat_g DOUBLE PRECISION NOT NULL,
    source_type VARCHAR(30) NOT NULL,
    fdc_id INTEGER,
    brand_name VARCHAR(255),
    brand_owner VARCHAR(255),
    notes TEXT,
    nutrition_snapshot JSON NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_meals_user_id ON meals(user_id);
CREATE INDEX IF NOT EXISTS ix_meals_logged_date ON meals(logged_date);

CREATE INDEX IF NOT EXISTS ix_user_profiles_user_id ON user_profiles (user_id);
